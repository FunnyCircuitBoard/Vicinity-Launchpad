// Builds src/coinart-metrics.js: the advance width (font units) of every character the two committed coin fonts draw
// (src/assets/fonts, scripts/coin-art/fonts.mjs). src/coinart.js fits the ticker and the city name with this table alone, so the
// browser, the Worker and the tests agree on every size without a renderer; test/coinart.test.js regenerates it from the font
// files and fails if the committed table differs.
//   node scripts/coin-art/metrics.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { readTtf } from "./ttf.mjs";

const root = (p) => fileURLToPath(new URL(`../../${p}`, import.meta.url));
export const FILES = { bold: "src/assets/fonts/SpaceGrotesk-Bold.ttf", medium: "src/assets/fonts/SpaceGrotesk-Medium.ttf" };

/** The metrics module's source text, from the font files as they are on disk now. */
export function metricsSource() {
  const fonts = {}, sha = {};
  for (const [k, p] of Object.entries(FILES)) {
    const bytes = readFileSync(root(p));
    fonts[k] = readTtf(bytes);
    sha[k] = createHash("sha256").update(bytes).digest("hex");
  }
  const { unitsPerEm, capHeight } = fonts.bold;
  if (fonts.medium.unitsPerEm !== unitsPerEm || fonts.medium.capHeight !== capHeight) throw new Error("the two fonts disagree on unitsPerEm or cap height");
  const data = { unitsPerEm, capHeight, fonts: sha, bold: fonts.bold.widths, medium: fonts.medium.widths };
  return `// GENERATED by scripts/coin-art/metrics.mjs from src/assets/fonts/*.ttf: do not edit (test/coinart.test.js rebuilds and compares it).
// Advance widths in font units of every character each coin font draws (no kerning, no ligatures: what resvg draws, exactly).
export default Object.freeze(${JSON.stringify(data)});
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(root("src/coinart-metrics.js"), metricsSource());
  console.log("src/coinart-metrics.js written");
}
