#!/usr/bin/env node
// Writes src/sol/dbc-config-data.js for the Worker (no anchor, no Meteora SDK there): the exact `create_config` instruction data of
// the Vicinity Meteora DBC config (vicinityConfigParams() defaults: SOL quote, 85 SOL target, 1.25% fee, 0.05 SOL launch fee,
// fee claimer and leftover receiver the dev wallet), and the PoolConfig account Meteora's real program writes for it, read back
// from litesvm (the pinned mainnet dump of DBC). The admin "City coins" tab builds setup step 3 from the first and, once the
// config is on chain, compares it byte for byte with the second, naming any field that differs.
//
//   node scripts/launchpad/worker-config-bytes.mjs           (from solana/) regenerate the file
//   node scripts/launchpad/worker-config-bytes.mjs --check   exit 1 when the committed file is stale
// Needs the program fixtures (npm run launchpad:fixtures) and target/deploy (anchor build), like the litesvm suite.
// solana/tests-launchpad/17-admin-builders.test.mjs checks the data against createConfigIx() and runs it against the real program.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { World, ADDRESSES } from '../../tests-launchpad/helpers.mjs';
import { vicinityConfigParams, createConfigIx, VICINITY_DEFAULTS } from '../../sdk/launchpad/config.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const solanaDir = join(here, '..', '..');
const OUT = join(solanaDir, '..', 'src', 'sol', 'dbc-config-data.js');
const PLACEHOLDER = '11111111111111111111111111111111';

export async function generate() {
  const params = vicinityConfigParams();
  const data = Buffer.from(createConfigIx({ config: PLACEHOLDER, quoteMint: ADDRESSES.wsol, payer: PLACEHOLDER, params }).data);
  const w = await World.create({ initLaunchpad: false, addConfig: false, initRewards: false });
  const cfg = await w.createDbcConfig({}, { params });
  const acc = w.account(cfg);
  const dbcSha = createHash('sha256').update(readFileSync(join(solanaDir, 'tests-launchpad', 'fixtures', 'programs', 'dbc.so'))).digest('hex');
  const d = VICINITY_DEFAULTS;
  const defaults = {
    quoteMint: ADDRESSES.wsol, feeClaimer: ADDRESSES.feeRecipient, leftoverReceiver: ADDRESSES.feeRecipient,
    migrationQuoteThreshold: String(BigInt(d.migrationQuoteThreshold) * 10n ** BigInt(d.quoteDecimals)), tradeFeeBps: d.tradeFeeBps,
    migratedPoolFeeBps: d.migratedPoolFeeBps, poolCreationFee: String(Math.round(d.poolCreationFeeSol * 1e9)), tokenDecimals: d.tokenDecimals,
    totalTokenSupply: String(d.totalTokenSupply), percentageSupplyOnMigration: d.percentageSupplyOnMigration,
  };
  return `/**
 * GENERATED by solana/scripts/launchpad/worker-config-bytes.mjs from solana/sdk/launchpad/config.mjs (vicinityConfigParams()
 * defaults) and Meteora DBC's pinned mainnet build (dbc.so sha256 ${dbcSha}). Do not edit: re-run the script
 * (solana/tests-launchpad/17-admin-builders.test.mjs fails when this file is stale).
 *   CREATE_CONFIG_DATA     the create_config instruction data (discriminator + ConfigParameters) of the Vicinity config
 *   EXPECTED_POOL_CONFIG   the ${acc.data.length}-byte PoolConfig account DBC writes for it (the same for every config address)
 */
export const DBC_CONFIG_DEFAULTS = Object.freeze(${JSON.stringify(defaults)});
export const CREATE_CONFIG_DATA = "${data.toString('base64')}";
export const EXPECTED_POOL_CONFIG = "${Buffer.from(acc.data).toString('base64')}";
export const POOL_CONFIG_RENT_LAMPORTS = ${String(acc.lamports)};
export const DBC_PROGRAM_SHA256 = "${dbcSha}";
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await generate();
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (now !== text) { console.error('src/sol/dbc-config-data.js is stale: run node scripts/launchpad/worker-config-bytes.mjs'); process.exit(1); }
    console.log('src/sol/dbc-config-data.js is current');
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
