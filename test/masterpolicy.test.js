/** Base58 text of 32 bytes all equal to `n`: a public-key-shaped test value with no private key behind it. */
function fakeKey(n) {
  const A = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
  const bytes = new Array(32).fill(n);
  let x = 0n;
  for (const b of bytes) x = x * 256n + BigInt(b);
  let s = "";
  while (x > 0n) { s = A[Number(x % 58n)] + s; x /= 58n; }
  for (const b of bytes) { if (b === 0) s = "1" + s; else break; }
  return s;
}

