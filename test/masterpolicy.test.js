test("every policy and deployment value is marked with a master section, and every mark points at a real value", () => {
  const leaves = (o, p) => (!isObj(o) || Object.keys(o).length === 0 ? [p] : Object.entries(o).flatMap(([k, v]) => leaves(v, `${p}.${k}`)));
  const get = (o, path) => path.split(".").reduce((x, k) => (isObj(x) && k in x ? x[k] : undefined), o);
  const marks = MASTER_POLICY.master_sections;
  assert.match(marks.policy_version, /^§16/);
  assert.match(marks.owner_delegation_date, /^§16/);
  const unmarked = [];
  for (const top of ["policy", "deployment"]) {
    for (const path of leaves(MASTER_POLICY[top], top)) {
      const parts = path.split(".");
      let mark;
      for (let i = parts.length; i >= 1 && mark === undefined; i--) {
        const v = get(marks, parts.slice(0, i).join("."));
        if (typeof v === "string") mark = v;
      }
      if (!(typeof mark === "string" && /^§\d{2}(?!\d)/.test(mark))) unmarked.push(path);
    }
  }
  assert.deepEqual(unmarked, []);
  const markPaths = (o, p) => (typeof o === "string" ? [p] : Object.entries(o).flatMap(([k, v]) => markPaths(v, `${p}.${k}`)));
  const dangling = [...markPaths(marks.policy, "policy"), ...markPaths(marks.deployment, "deployment")].filter((p) => get(MASTER_POLICY, p) === undefined);
  assert.deepEqual(dangling, []);
});

